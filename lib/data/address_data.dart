class AddressService {
  static List<String> getProvinces() {
    final seen = <String>{};
    final result = <String>[];
    for (final e in kThaiAddress) {
      if (seen.add(e[2])) result.add(e[2]);
    }
    result.sort((a, b) {
      if (a == 'กรุงเทพมหานคร') return -1;
      if (b == 'กรุงเทพมหานคร') return 1;
      return a.compareTo(b);
    });
    return result;
  }

  static List<String> getDistricts(String province) {
    final seen = <String>{};
    final result = <String>[];
    for (final e in kThaiAddress) {
      if (e[2] == province && seen.add(e[1])) result.add(e[1]);
    }
    result.sort();
    return result;
  }

  static List<Map<String, String>> getSubdistricts(String province, String district) {
    final result = <Map<String, String>>[];
    for (final e in kThaiAddress) {
      if (e[2] == province && e[1] == district) {
        result.add({'name': e[0], 'zip': e[3]});
      }
    }
    result.sort((a, b) => a['name']!.compareTo(b['name']!));
    return result;
  }

  static String getZip(String province, String district, String subdistrict) {
    for (final e in kThaiAddress) {
      if (e[2] == province && e[1] == district && e[0] == subdistrict) {
        return e[3];
      }
    }
    return '';
  }
}
